function HsvToRgb([double]$ppH, [double]$ppS, [double]$ppV) {
  $ppH = (($ppH % 360) + 360) % 360
  $c = $ppV * $ppS
  $hp = $ppH / 60.0
  $x2 = $c * (1 - [Math]::Abs(($hp % 2) - 1))
  $rr = 0.0; $gg = 0.0; $bb = 0.0
  if ($hp -lt 1) { $rr = $c; $gg = $x2 }
  elseif ($hp -lt 2) { $rr = $x2; $gg = $c }
  elseif ($hp -lt 3) { $gg = $c; $bb = $x2 }
  elseif ($hp -lt 4) { $gg = $x2; $bb = $c }
  elseif ($hp -lt 5) { $rr = $x2; $bb = $c }
  else { $rr = $c; $bb = $x2 }
  $m = $ppV - $c
  return @([int][Math]::Round(($rr + $m) * 255), [int][Math]::Round(($gg + $m) * 255), [int][Math]::Round(($bb + $m) * 255))
}
function H01([double]$na, [double]$nb, [double]$nc) { $hx = [Math]::Sin($na * 12.9898 + $nb * 78.233 + $nc * 37.719) * 43758.5453; return ($hx - [Math]::Floor($hx)) }
function CL([double]$cv) { if ($cv -lt 0) { return 0.0 } elseif ($cv -gt 1) { return 1.0 } else { return $cv } }

# 所有年龄统一走同一套模板做整体缩放：age0 自然得到 4 行的小尖芽，不再单独写幼苗模板
function Build-Leaf {
  param([string[]]$A, [string[]]$B, [string[]]$C, [string[]]$D, [int]$Age, $Pal)
  $bmp = New-Object System.Drawing.Bitmap(16, 16)
  $src = @($A, $B, $C, $D)
  $len = @(4, 6, 8, 10, 13, 16)[$Age]
  for ($k = 0; $k -lt 4; $k++) {
    $tpl = $src[$k]
    for ($i = 0; $i -lt $len; $i++) {
      $srcRow = [int][Math]::Round($i / [double]($len - 1) * 15)
      $row = $tpl[$srcRow]
      if ($null -eq $row) { continue }
      $v = 16 - $len + $i
      for ($u = 0; $u -lt 4; $u++) {
        if ($u -ge $row.Length) { continue }
        $ch = $row.Substring($u, 1)
        if ($ch -eq '.') { continue }
        $c = $Pal[[int]$ch - 1]
        $bmp.SetPixel(($k * 4 + $u), $v, [System.Drawing.Color]::FromArgb(255, $c[0], $c[1], $c[2]))
      }
    }
  }
  return $bmp
}
function Build-Head {
  param([int]$Seed, [double]$Hue, [double]$Sat, [double]$Val, [double]$Rx = 6.35, [double]$Ry = 5.85, [double]$Rough = 1.0, [switch]$Curd, [double]$CurdH = 60, [double]$CurdS = 0.08, [double]$CurdV = 0.9)
  $bmp = New-Object System.Drawing.Bitmap(16, 16)
  for ($y = 0; $y -lt 16; $y++) {
    for ($x = 0; $x -lt 16; $x++) {
      $nx = ($x + 0.5 - 7.4) / $Rx
      $ny = ($y + 0.5 - 7.8) / $Ry
      $d = [Math]::Sqrt($nx * $nx + $ny * $ny)
      $th = [Math]::Atan2($ny, $nx)
      $edge = 1.0 + $Rough * (0.105 * [Math]::Sin(3 * $th + 0.7 + $Seed) + 0.068 * [Math]::Sin(5 * $th + 2.1) + 0.045 * [Math]::Sin(8 * $th + 0.3 * $Seed))
      if ($d -gt $edge) { continue }
      $n1 = H01 $x $y $Seed
      $rim = CL (($edge - $d) / 0.18)
      $sh = 0.40 + 0.60 * [Math]::Pow($rim, 0.50)
      $sh *= (1.0 + 0.50 * (-$nx * 0.40 - $ny * 0.70))
      $hh = $Hue; $ss = $Sat; $vv = $Val
      if ($Curd) {
        $gx = [Math]::Floor($x / 2.0); $gy = [Math]::Floor($y / 2.0)
        $g = H01 $gx $gy ($Seed + 9)
        $sh *= (0.68 + 0.56 * $g)
        $sh *= (1.0 + 0.06 * [Math]::Sin($x * 1.7 + $y * 2.3))
        $sh *= (0.76 + 0.32 * (CL (1.2 - $d)))
        $hh = $CurdH; $ss = $CurdS; $vv = $CurdV
      }
      else {
        $ang = $th + 0.55 * $d
        $rv = ($ang / (2 * [Math]::PI)) * 6.0 + 0.5
        $rvf = $rv - [Math]::Floor($rv)
        $dv = [Math]::Abs($rvf - 0.5)
        if ($dv -lt 0.08) { $sh *= (1.0 + 0.42 * (1.0 - $dv / 0.08)) }
        $lay = $d * 2.6 + 0.20 * [Math]::Sin(4 * $th + 1.1)
        $fr = $lay - [Math]::Floor($lay)
        if ($fr -lt 0.12) { $sh *= (0.32 + 0.68 * $fr / 0.12) }
      }
      $sh *= (0.94 + 0.12 * $n1)
      $cc = HsvToRgb ($hh + 4.0 * (0.5 - $n1)) (CL ($ss + 0.06 * ($n1 - 0.5))) (CL ($vv * $sh))
      $bmp.SetPixel($x, $y, [System.Drawing.Color]::FromArgb(255, $cc[0], $cc[1], $cc[2]))
    }
  }
  return $bmp
}
function Save-Bmp($bmp, [string]$name) {
  $bmp.Save((Join-Path $outDir ($name + '.png')), [System.Drawing.Imaging.ImageFormat]::Png)
  $bmp.Dispose()
}

